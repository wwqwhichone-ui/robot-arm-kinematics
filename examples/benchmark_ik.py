"""Benchmark numerical IK on the UR5: random reachable poses, with and without restarts.

Run:  python examples/benchmark_ik.py [--n 500]
Targets are generated by FK from random joint vectors, so every target is reachable.
"""

from __future__ import annotations

import argparse
import platform
import time

import numpy as np

from armkin import pose_error, ur5


def run(n: int, restarts: int, seed: int) -> dict:
    arm = ur5()
    rng = np.random.default_rng(seed)
    targets = [arm.fk(rng.uniform(-np.pi, np.pi, 6)) for _ in range(n)]
    ok, iters, pos_err, t_total = 0, [], [], 0.0
    for T in targets:
        t0 = time.perf_counter()
        res = arm.ik(T, q0=np.zeros(6), restarts=restarts, rng=rng)
        t_total += time.perf_counter() - t0
        if res.success:
            ok += 1
            iters.append(res.iterations)
            pos_err.append(np.linalg.norm(pose_error(arm.fk(res.q), T)[:3]))
    return {
        "restarts": restarts,
        "success": ok / n,
        "median_iters": float(np.median(iters)) if iters else float("nan"),
        "max_pos_err_mm": 1000 * float(np.max(pos_err)) if pos_err else float("nan"),
        "ms_per_solve": 1000 * t_total / n,
    }


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--n", type=int, default=500)
    ap.add_argument("--seed", type=int, default=0)
    args = ap.parse_args()
    print(f"UR5 full-pose IK, {args.n} random reachable targets, seed {args.seed}")
    print(f"machine: {platform.machine()} / Python {platform.python_version()} / NumPy {np.__version__}\n")
    print("| restarts | success | median iterations | max position error | time / solve |")
    print("| --- | --- | --- | --- | --- |")
    for r in (0, 5):
        s = run(args.n, r, args.seed)
        print(
            f"| {s['restarts']} | {100 * s['success']:.1f}% | {s['median_iters']:.0f} | "
            f"{s['max_pos_err_mm']:.3f} mm | {s['ms_per_solve']:.1f} ms |"
        )


if __name__ == "__main__":
    main()
